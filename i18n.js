  function getLanguage() {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (SUPPORTED_LANGUAGES.has(saved)) return saved;
    return navigator.language?.toLowerCase().startsWith("th") ? "th" : "zh-TW";
  }

  let language = getLanguage();

  function translate(value) {
    if (language !== "th" || typeof value !== "string") return value;
    const exact = THAI.get(value.trim());
    if (exact) return value.replace(value.trim(), exact);
    let translated = value;
    PHRASES.forEach(([source, target]) => { translated = translated.split(source).join(target); });
    return translated;
  }

  function shouldSkip(node) {
    const parent = node.nodeType === Node.TEXT_NODE
      ? node.parentElement
      : (node.nodeType === Node.ELEMENT_NODE ? node : node.parentElement);
    return Boolean(parent?.closest?.("script, style, svg, [data-i18n-skip]"));
  }

  function translateTextNode(node) {
    if (shouldSkip(node) || !node.nodeValue?.trim()) return;
    let source = originalText.get(node);
    if (source === undefined) {
      source = node.nodeValue;
      originalText.set(node, source);
    } else if (!applyingLanguage && node.nodeValue !== (language === "th" ? translate(source) : source)) {
      source = node.nodeValue;
      originalText.set(node, source);
    }
    const next = language === "th" ? translate(source) : source;
    if (node.nodeValue !== next) node.nodeValue = next;
  }

  function translateAttribute(element, attribute) {
    if (shouldSkip(element) || !element.hasAttribute(attribute)) return;
    let saved = originalAttributes.get(element);
    if (!saved) {
      saved = {};
      originalAttributes.set(element, saved);
    }
    const current = element.getAttribute(attribute);
    let source = saved[attribute];
    if (source === undefined) {
      source = current;
      saved[attribute] = source;
    } else if (!applyingLanguage && current !== (language === "th" ? translate(source) : source)) {
      source = current;
      saved[attribute] = source;
    }
    const next = language === "th" ? translate(source) : source;
    if (current !== next) element.setAttribute(attribute, next);
  }

  function translateSubtree(root) {
    if (!root || shouldSkip(root)) return;
    if (root.nodeType === Node.TEXT_NODE) return translateTextNode(root);
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
    let textNode;
    while ((textNode = walker.nextNode())) translateTextNode(textNode);
    const elements = root.matches?.("[title], [placeholder], [aria-label]") ? [root] : [];
    root.querySelectorAll?.("[title], [placeholder], [aria-label]").forEach((element) => elements.push(element));
    elements.forEach((element) => ["title", "placeholder", "aria-label"].forEach((attribute) => translateAttribute(element, attribute)));
  }

  function updateToggle() {
    const button = document.getElementById("languageToggleBtn");
    const label = document.getElementById("languageToggleLabel");
    if (label) label.textContent = language === "th" ? "繁中" : "ไทย";
    if (button) {
      const description = language === "th" ? "เปลี่ยนเป็นภาษาจีนตัวเต็ม" : "切換為泰文";
      button.title = description;
      button.setAttribute("aria-label", description);
      button.dataset.language = language;
    }
  }

  function applyLanguage(nextLanguage) {
    language = SUPPORTED_LANGUAGES.has(nextLanguage) ? nextLanguage : "zh-TW";
    localStorage.setItem(STORAGE_KEY, language);
    document.documentElement.lang = language;
    applyingLanguage = true;
    try {
      translateSubtree(document.body);
      document.title = language === "th"
        ? "CHIN CHUN - ระบบแบบวิศวกรรมและผังอุปกรณ์โรงงาน (V2.9.0)"
        : "金讚科技 - 廠房正式工程圖與模組化設備配置系統 (V2.9.0)";
      updateToggle();
    } finally {
      applyingLanguage = false;
    }
    document.dispatchEvent(new CustomEvent("chinchun:languagechange", { detail: { language } }));
  }

